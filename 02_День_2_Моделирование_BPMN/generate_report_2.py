    add_p("На первом занятии я выполнил анализ предметной области боулинг- и бильярдного клуба, выделил 9 ключевых сущностей и зафиксировал особое требование варианта №4 (лимит 6 человек на дорожку и расчет стыка дневного/вечернего тарифов). На втором занятии эти требования необходимо развернуть в детальные бизнес-процессы в нотации BPMN 2.0, найти в них узкие места и показать, как изменится работа заведения после запуска веб-сайта на Django.")
    
