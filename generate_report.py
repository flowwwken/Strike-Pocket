import docx
from docx.shared import Pt, Inches, Mm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT, WD_ALIGN_VERTICAL
from docx.oxml import OxmlElement, parse_xml
from docx.oxml.ns import qn, nsdecls

def create_humanized_report():
    doc = docx.Document()
    
    # 1. Поля по ГОСТ 7.32 (левое 30 мм, правое 15 мм, верхнее 20 мм, нижнее 20 мм)
    section = doc.sections[0]
    section.page_width = Mm(210)
    section.page_height = Mm(297)
    section.top_margin = Mm(20)
    section.bottom_margin = Mm(20)
    section.left_margin = Mm(30)
    section.right_margin = Mm(15)
    
    # Титульный лист не должен иметь номер страницы в колонтитуле (different_first_page_header_footer)
    section.different_first_page_header_footer = True
    
    # Базовый стиль шрифта
    style = doc.styles['Normal']
    font = style.font
    font.name = 'Times New Roman'
    font.size = Pt(14)
    font.color.rgb = RGBColor(0, 0, 0)
    p_format = style.paragraph_format
    p_format.line_spacing = 1.5
    p_format.space_before = Pt(0)
    p_format.space_after = Pt(0)
    p_format.first_line_indent = Mm(12.5)
    p_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    
    # Настройка колонтитула со 2-й страницы (нумерация страниц)
    footer = section.footer
    f_p = footer.paragraphs[0]
    f_p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    f_p.paragraph_format.first_line_indent = Mm(0)
    f_run = f_p.add_run()
    f_run.font.name = 'Times New Roman'
    f_run.font.size = Pt(11)
    
